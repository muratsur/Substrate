"""Sector C room tone, so the Audio anomaly (Socket_Audio_SewerSilence pauses Amb_RoomTone_Global) can be noticed.
Uses AMB_RoomTone_Hum (generated by generate_room_tone.py; the old AMB_* loops are all one water/wading recording that
the player disliked). Loops, auto-activates, non-spatialized, confined to a box over Sector C with a 1500-unit fade, so
Sector D keeps its own hum and the silence before C-06. Previous: AMB_SewerRoomTone_Loop, autoactivate off, volume 0."""
import sys, json
sys.path.insert(0, '_tools')
import mcpx as M
M.init()
SND = '/Game/Substrate/Audio/AMB_RoomTone_Hum.AMB_RoomTone_Hum'
C = '/Game/Substrate/Maps/L_SectorC.L_SectorC:PersistentLevel.AmbientSound_0.AudioComponent0'
gp = lambda ref, props: json.loads(json.loads(M.call('call_tool', {'toolset_name': M.OBJ, 'tool_name': 'get_properties', 'arguments': {'instance': {'refPath': ref}, 'properties': props}}))['returnValue'])
sp = lambda ref, vals: M.call('call_tool', {'toolset_name': M.OBJ, 'tool_name': 'set_properties', 'arguments': {'instance': {'refPath': ref}, 'values': json.dumps(vals)}})
sp(SND, {'bLooping': True})
print('sound', gp(SND, ['bLooping', 'Duration']))
ao = gp(C, ['AttenuationOverrides'])['AttenuationOverrides']
ao.update({'bAttenuate': True, 'bSpatialize': False, 'attenuationShape': 'Box',
           'attenuationShapeExtents': {'x': 11000, 'y': 8000, 'z': 3000}, 'falloffDistance': 1500})
for v in ({'Sound': {'refPath': SND}}, {'bAutoActivate': True}, {'VolumeMultiplier': 0.5}, {'bOverrideAttenuation': True}, {'AttenuationOverrides': ao}):
    sp(C, v)
a = gp(C, ['Sound', 'bAutoActivate', 'VolumeMultiplier', 'bOverrideAttenuation', 'AttenuationOverrides'])
print({k: a[k] for k in ('Sound', 'bAutoActivate', 'VolumeMultiplier', 'bOverrideAttenuation')}, a['AttenuationOverrides']['attenuationShape'], a['AttenuationOverrides']['attenuationShapeExtents'], a['AttenuationOverrides']['falloffDistance'])
print(M.call('call_tool', {'toolset_name': M.AT, 'tool_name': 'save_assets', 'arguments': {'asset_paths': []}}))
